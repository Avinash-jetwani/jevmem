#!/usr/bin/env python3
"""Write pane/tests/fixtures.ts from the files in pane/tests/fixtures/ (a `claude plugin test` runs with no file system,
so the fixtures are strings in a module), with the e2e harness's prompt behind each captured recall file, and check that
each prompt's sha1 (16 hex, as the hook writes `prompt_hash`) is the file's. Run from the repository root:
    python3 scripts/pane-fixtures.py"""
import hashlib, json, os, sys
F = "pane/tests/fixtures"
PROMPTS = {
    "recall-served-2.json": "The tsc compile step slows down my edit-run loop. Can we run src/app.ts directly with node and skip it? Do what you think is best, then answer in two or three sentences.",
    "recall-served-1-gated.json": "Try running src/app.ts directly with node --experimental-strip-types instead of compiling it with tsc first. Run it once. If it doesn't work, drop the idea: change no files, keep the tsc build, and tell me in one or two sentences what you tried and why it failed.",
    "recall-served-1.json": "Actually, we're submitting to the Chrome Web Store this week — the privacy page is live now.",
    "recall-served-0.json": "Decision: the extension ships as a sideload zip only, no Chrome Web Store yet.",
    "recall-no-lines.json": "Decision: the extension ships as a sideload zip only, no Chrome Web Store yet.",
    "recall-bad-id.json": "Actually, we're submitting to the Chrome Web Store this week — the privacy page is live now.",
}
bad = []
for name, prompt in PROMPTS.items():
    want = json.load(open(os.path.join(F, name)))["prompt_hash"]
    got = hashlib.sha1(prompt.encode()).hexdigest()[:16]
    if got != want:
        bad.append(f"{name}: the prompt hashes to {got}, the file says {want}")
if bad:
    print("\n".join(bad), file=sys.stderr); sys.exit(1)
out = ["// Generated by scripts/pane-fixtures.py from the files in fixtures/ (see fixtures/README.md): a test runs with no",
       "// file system, so the files are strings here. Do not edit by hand.",
       "export const fixtures: Record<string, string> = {"]
for name in sorted(os.listdir(F)):
    if name.endswith(".md"):
        continue
    out.append(f"  {json.dumps(name)}: {json.dumps(open(os.path.join(F, name)).read())},")
out.append("}")
out.append("")
out.append("// The prompts behind the captured recall files (the e2e harness's), so a test's prompt hashes to the file's prompt_hash.")
out.append("export const prompts: Record<string, string> = {")
for name, prompt in PROMPTS.items():
    out.append(f"  {json.dumps(name)}: {json.dumps(prompt)},")
out.append("}")
open("pane/tests/fixtures.ts", "w").write("\n".join(out) + "\n")
print(f"pane/tests/fixtures.ts: {len([n for n in os.listdir(F) if not n.endswith('.md')])} files, {len(PROMPTS)} prompts, every hash matches")
